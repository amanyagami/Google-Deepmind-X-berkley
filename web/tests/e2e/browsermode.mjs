// Pure web app (no companion): recorded journey, measured reference run, then a full in-browser measurement.
import { chromium } from 'playwright-core'
import fs from 'node:fs'
import path from 'node:path'
const OUT = process.argv[2], URL = process.argv[3]
fs.mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true, args: ['--headless=new', '--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=d3d11', '--enable-unsafe-webgpu'] })
const page = await browser.newPage({ viewport: { width: 1480, height: 900 } })
const problems = []
page.on('pageerror', (e) => problems.push(`[pageerror] ${e.message}`))
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource|ERR_CONNECTION_REFUSED|onnxruntime/.test(m.text())) problems.push(`[console] ${m.text()}`) })
const shot = async (n) => { await page.screenshot({ path: path.join(OUT, n + '.png') }); console.log('shot', n) }
const hw = (fn, a) => page.evaluate(fn, a)
await page.goto(URL, { waitUntil: 'domcontentloaded' })
await page.waitForFunction(() => window.__hw?.getState().info, null, { timeout: 30000, polling: 300 })
console.log('source:', await hw(() => window.__hw.getState().source), '| gpu:', await hw(() => window.__hw.getState().info.gpus[0]?.name))
await page.click('#sec-power .mtl button:has-text("Play a recorded journey")')
await page.waitForFunction(() => window.__hw.getState().journey, null, { timeout: 30000, polling: 300 })
await hw(() => { const s = window.__hw.getState(); s.pause(); s.setPlayhead(s.tl.segs.find((x) => x.id === 'decode').v0 + 1) }); await page.waitForTimeout(1500)
console.log('recorded caption:', (await page.locator('.caption').innerText()).replace(/\s+/g, ' ').slice(0, 140))
await shot('b-recorded-journey')
await hw(() => window.__hw.getState().dive(['ram'])); await page.waitForTimeout(1500)
console.log('ram dive:', (await page.locator('.caption.dive').innerText()).replace(/\s+/g, ' ').slice(0, 400))
await shot('b-ram-kv')
await hw(() => window.__hw.getState().back())
await page.click('header .seg button:has-text("Machine")'); await page.waitForTimeout(800)
await page.click('#sec-power .phud button:has-text("Replay a measured run")')
await page.waitForTimeout(2500)
console.log('reference hud:', (await page.locator('#sec-power .phud').innerText()).replace(/\s+/g, ' ').slice(0, 200))
await shot('b-reference-replay')
await hw(() => window.__hw.getState().setAiInBrowser(true))
await page.click('#sec-power .phud button:has-text("Run the test")')
await page.waitForFunction(() => !window.__hw.getState().benchRunning && window.__hw.getState().power && !window.__hw.getState().power.reference, null, { timeout: 600000, polling: 1000 })
const r = await hw(() => { const s = window.__hw.getState(); return { bench: Object.fromEntries(Object.entries(s.bench).map(([k, v]) => [k, v?.gflops ?? v?.copy_gbps ?? v?.gbps ?? v?.mbps ?? v?.tps ?? (Array.isArray(v) ? Math.max(...v.map((c) => c.gbps)) : v)])), ai: s.bench.ai?.device, est: s.power.estimated, err: s.benchErr } })
console.log('browser run:', JSON.stringify(r))
if (!(await page.locator('#sec-power .tabs').count())) await page.click('#sec-power .detbtn')
await page.click('#sec-power .tabs button:has-text("Score")'); await page.waitForTimeout(1200)
console.log('score:', (await page.locator('.hero-score').innerText()).replace(/\s+/g, ' ').slice(0, 30), '|', (await page.locator('.ccard .chead').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ')).join(' | '))
await shot('b-browser-score')
console.log('problems:', problems.length ? '\n  ' + [...new Set(problems)].join('\n  ') : 'none')
await browser.close()
